/**
 * Regenerates the mechanical half of every Journal > Encounters entry from the
 * live data files, so the numbers in the journal cannot drift from the game.
 *
 * Run:  node tools/gen_encounter_journal.js
 *
 * Each entry file is split into two halves:
 *   - Everything OUTSIDE the <!-- GEN:START --> / <!-- GEN:END --> markers is
 *     hand-authored prose (the synopsis, how the NPCs interact, flavour). This
 *     script never touches it.
 *   - Everything INSIDE the markers is derived from data/combatScenarios.js,
 *     data/enemyTypes.js and data/skills.js and is rewritten wholesale.
 *
 * Adding a new encounter or roster is therefore additive: drop the scenario in
 * combatScenarios.js, add it to SCENARIO_DOCS / ADVERSARY_DOCS below, rerun the
 * script, then write the synopsis above the marker.
 *
 * Deliberately EXCLUDED (dev-facing balance dials, not player knowledge):
 *   damageMultiplierPct, buildupMultiplierPct, aiProfile, mpRegenPerTurn.
 */
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const MD_DIR = join(ROOT, 'data/journal/md');
const OUT_DIR = join(MD_DIR, 'encounters');
const INDEX = join(MD_DIR, 'index.json');

const { COMBAT_SCENARIOS } = await import('../data/combatScenarios.js');
const { ENEMY_TYPES } = await import('../data/enemyTypes.js');
const { SKILLS } = await import('../data/skills.js');
const { Items: ITEMS } = await import('../data/items.js');

/** 'zafaar_amulet_lacerate' -> "Zafaar Pendant of Lacerations" */
function itemName(id) {
  const it = ITEMS[id];
  if (!it) return id;
  const affix = it.fixedAffix && it.fixedAffix.key ? ' ' + it.fixedAffix.key : '';
  return (it.name || id) + affix;
}

const NL = String.fromCharCode(10);
const GEN_START = '<!-- GEN:START - regenerated by tools/gen_encounter_journal.js, do not hand-edit below -->';
const GEN_END = '<!-- GEN:END -->';

